import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
import ts from "typescript";
const compiled=ts.transpileModule(readFileSync("src/lib/game/model.ts","utf8"),{compilerOptions:{esModuleInterop:true,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
vm.runInNewContext(compiled,{exports:mod.exports,module:mod,require:createRequire(new URL("../src/lib/game/model.ts",import.meta.url))});
const {newGame, safeLoad, nextDay, canSleep, interactDoor, movePlayer, chooseSocial, meetNpc, applyFarmTool, bondLevel, playerLevel}=mod.exports;
let s=newGame();
assert.equal(nextDay(s),s,"outdoor sleep must not advance the day");
assert.equal(canSleep(s),false);
s=interactDoor({...s,player:{x:3,y:5,dir:"up"}});
assert.equal(s.location,"home");
assert.equal(nextDay(s),s,"inside room but away from bed cannot sleep");
assert.equal(applyFarmTool(s,"hoe").state,s,"cannot farm inside");
assert.equal(movePlayer({...s,player:{x:9,y:8,dir:"up"}},"up").player.y,8,"bed collision");
s={...s,player:{x:9,y:8,dir:"up"},stats:{...s.stats,stamina:0},plots:[{x:3,y:8,stage:0,watered:true}]};
assert.equal(canSleep(s),true);
s=nextDay(s);
assert.equal(s.day,2);assert.equal(s.stats.stamina,100);assert.equal(s.stats.nights,1);assert.equal(s.plots[0].stage,1);
assert.equal(safeLoad(JSON.parse(JSON.stringify(s))).location,"home","home save restores");
s=interactDoor({...s,player:{x:12,y:12,dir:"down"}});
assert.equal(s.location,"field");assert.equal(s.player.y,5);
for(const npc of ["A03","C01","C08"]){
 let g=newGame();
 assert.ok(meetNpc(g,npc).choices.length>=3);
 assert.equal(chooseSocial(g,npc,"confide").state,g,"private dialogue locked");
 let r=chooseSocial(g,npc,"help");g=r.state;
 assert.equal(g.bonds[npc].points,20);assert.equal(r.emotion,"surprised");
 assert.equal(chooseSocial(g,npc,"help").state.bonds[npc].points,20,"no repeat points same day");
 g={...g,day:2};g=chooseSocial(g,npc,"dismiss").state;
 assert.equal(g.bonds[npc].points,12);
 assert.ok(["sad","annoyed"].includes(g.bonds[npc].mood));
 assert.equal(g.stats.conversations,2);
 for(let d=3;d<=12;d++)g=chooseSocial({...g,day:d},npc,"help").state;
 assert.equal(bondLevel(g.bonds[npc].points),2);
 assert.equal(chooseSocial({...g,day:13},npc,"confide").emotion,"worried");
 assert.ok(playerLevel(g)>1);
 const restored=safeLoad(JSON.parse(JSON.stringify(g)));assert.equal(restored.bonds[npc].points,g.bonds[npc].points);
}
const legacy=newGame();delete legacy.stats;delete legacy.bonds;delete legacy.location;
assert.equal(safeLoad(legacy).stats.stamina,100);
assert.equal(safeLoad(legacy).bonds.A03.points,0);
assert.equal(safeLoad({...newGame(),stats:{...newGame().stats,stamina:101}}),null);
assert.equal(safeLoad({...newGame(),bonds:{A03:{points:999999}}}),null);
assert.equal(safeLoad({...newGame(),location:"unknown"}),null);
assert.equal(applyFarmTool({...newGame(),stats:{...newGame().stats,stamina:0}},"hoe").state.stats.actions,0);
console.log("Life systems: sleep, collisions, social branches, daily caps, unlocks, stats, old-save migration: PASS");
