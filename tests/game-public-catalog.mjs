import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const report=execFileSync(process.execPath,['scripts/game-characters/verify-public-catalog.mjs'],{encoding:'utf8'});
assert.match(report,/PASS: public fictional 248 NPC catalog/);
const rosterReader=readFileSync('src/lib/game/private-residents.ts','utf8');
assert.ok(rosterReader.includes('npc-public-roster.json'),'missing canonical public roster fallback');
const ui=readFileSync('src/app/game/character-gallery.tsx','utf8');
assert.ok(ui.includes('/game/data/npc/'),'YZ Phone does not load public dossier by canonical ID');
assert.ok(ui.includes('public-fictional-draft'),'YZ Phone must mark public lore as draft');
const phone=readFileSync('src/app/game/phone-wargapedia.tsx','utf8');
const client=readFileSync('src/app/game/game-client.tsx','utf8');
const guide=readFileSync('src/lib/game/public-wargapedia.ts','utf8');
assert.ok(phone.includes('/game/data/npc/index.json'), 'phone Wargapedia must load 248-index');
assert.ok(phone.includes('/game/data/npc/'), 'phone Wargapedia must fetch each dossier on demand');
assert.ok(phone.includes('WARGAPEDIA_CATEGORIES.map'), 'phone must show all twelve public lore sections');
assert.ok(phone.includes('WARGAPEDIA_HIDDEN_FIELDS'), 'phone must avoid exposing internal editorial metadata');
assert.ok(phone.includes('onSelect(person.id)'), 'phone list must open canonical ID, not legacy ID');
assert.ok(phone.includes('Tidak perlu berkenalan atau naik level'), 'phone must explain unrestricted access');
assert.doesNotMatch(phone,/bondLevel|game\\.bonds|bond\\.points|legacyApproved/, 'public Wargapedia may not gate on friendship or legacy saves');
assert.ok(client.includes('name: "Wargapedia"'), 'Wargapedia must appear as an app on YZ Phone');
assert.ok(client.includes('<PhoneWargapedia selectedId={selectedWikiId}'), 'YZ Phone must embed Wargapedia, not redirect out of game');
assert.ok(client.includes('setSelectedWikiId(null)'), 'phone navigation must support back to index');
assert.ok(ui.includes('onOpenWargapedia'), 'Warga contacts must link to the embedded public wiki');
assert.equal((guide.match(/\\['0[1-9]_|'1[0-2]_/g)||[]).length>=12,true,'all 12 shared category labels must exist');
console.log('PASS: 248 public fictional dossiers, 12 phone chapters, search and unrestricted Wargapedia navigation');
