import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const read = (p) => readFileSync(p,"utf8");
const nav=read("src/components/farm-bottom-nav.tsx");
const home=read("src/app/home/page.tsx");
const op=read("src/app/operasional/page.tsx");
assert.match(nav,/href:'\/home'/);
assert.match(nav,/href:'\/anggaran'/);
assert.match(nav,/href:'\/keuangan\/bon\/baru'/);
assert.match(nav,/href:'\/pertanian'/);
assert.match(nav,/href:'\/panen'/);
assert.doesNotMatch(nav,/href:'\/catat'|href:'\/lahan'|href:'\/laporan'/);
assert.match(home,/farm_projects/);
assert.match(home,/budget_items/);
assert.match(home,/href="\/operasional"/);
assert.doesNotMatch(home,/import Workspace/);
assert.match(op,/import Workspace/);
assert.match(op,/view="home"/);
console.log("Additive UX contract: old routes and navigation preserved; new module isolated.");
