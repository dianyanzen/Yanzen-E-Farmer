import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
import {buildSync} from 'esbuild';
const f=new URL('../src/lib/game/model.ts',import.meta.url), mod={exports:{}};
const js=ts.transpileModule(readFileSync(f,'utf8'),{compilerOptions:{esModuleInterop:true,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(js,{module:mod,exports:mod.exports,require:createRequire(f)},{timeout:1500});
const {newGame,irrigateGarden,getActionContext,safeLoad,applyFarmTool,nextDay}=mod.exports;
const s={...newGame(),location:'field',player:{x:3,y:8,dir:'left'},plots:[{x:3,y:8,stage:0,watered:false},{x:4,y:8,stage:2,watered:true},{x:5,y:8,stage:-1,watered:false},{x:6,y:8,stage:3,watered:false}]};
assert.equal(getActionContext(s).kind,'irrigate');
const tapModule={exports:{}};
const tapCode=buildSync({entryPoints:['src/lib/game/tap-navigation.ts'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
vm.runInNewContext(tapCode,{module:tapModule,exports:tapModule.exports},{timeout:1500});
assert.equal(tapModule.exports.planTapRoute(s,2,8)?.interact,true,'touching the faucet must plan an interaction');
const r=irrigateGarden(s);assert.equal(r.state.plots[0].watered,true);assert.equal(r.state.plots[1].watered,true);assert.equal(r.state.plots[2].watered,false);assert.equal(r.state.plots[3].watered,false);assert.equal(r.state.minutes,s.minutes+10);
assert.equal(r.state.irrigationOpen,true);
const closed=irrigateGarden(r.state).state;assert.equal(closed.irrigationOpen,false);assert.equal(closed.plots[0].watered,true,'closing must not undo watering');
assert.equal(irrigateGarden(closed).state.irrigationOpen,true,'faucet can be reopened without crops needing water');
assert.equal(irrigateGarden({...s,location:'home'}).state.location,'home');
const loaded=safeLoad(JSON.parse(JSON.stringify(r.state)));assert.equal(loaded.plots[0].watered,true);assert.equal(loaded.irrigationOpen,true,'open faucet persists');
assert.equal(safeLoad({...JSON.parse(JSON.stringify(s)),irrigationOpen:'yes'}),null,'reject invalid flag');
assert.ok(safeLoad(JSON.parse(JSON.stringify(s))),'old save without faucet flag loads');
const plant=applyFarmTool({...r.state,player:{x:5,y:9,dir:'up'}},'seed');assert.equal(plant.state.plots[2].watered,true,'open faucet supplies new plants');
const sleep={...r.state,location:'home',player:{x:9,y:8,dir:'up'}};assert.equal(nextDay(sleep).plots[0].watered,true,'open faucet remains active next morning');
console.log('PASS: faucet toggle, channel access, crops, day transition and save migration');
