import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
import {buildSync} from 'esbuild';
const f=new URL('../src/lib/game/model.ts',import.meta.url), mod={exports:{}};
const js=ts.transpileModule(readFileSync(f,'utf8'),{compilerOptions:{esModuleInterop:true,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(js,{module:mod,exports:mod.exports,require:createRequire(f)},{timeout:1500});
const {newGame,irrigateGarden,getActionContext,safeLoad,applyFarmTool,nextDay}=mod.exports;
const s={...newGame(),location:'field',player:{x:3,y:8,dir:'left'},plots:[{x:3,y:8,stage:0,watered:false},{x:4,y:8,stage:2,watered:true},{x:5,y:8,stage:-1,watered:false},{x:6,y:8,stage:3,watered:false}]};
assert.equal(getActionContext(s).kind,'irrigate');
const tapModule={exports:{}};
const tapCode=buildSync({entryPoints:['src/lib/game/tap-navigation.ts'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
vm.runInNewContext(tapCode,{module:tapModule,exports:tapModule.exports},{timeout:1500});
assert.equal(tapModule.exports.planTapRoute(s,2,8)?.interact,true,'touching the faucet must plan an interaction');
const r=irrigateGarden(s);assert.equal(r.state.plots[0].watered,true);assert.equal(r.state.plots[1].watered,true);assert.equal(r.state.plots[2].watered,false);assert.equal(r.state.plots[3].watered,true);assert.equal(r.state.minutes,s.minutes+10);
assert.equal(r.state.irrigationOpen,true);
const closed=irrigateGarden(r.state).state;assert.equal(closed.irrigationOpen,false);assert.equal(closed.plots[0].watered,true,'closing must not undo watering');
assert.equal(irrigateGarden(closed).state.irrigationOpen,true,'faucet can be reopened without crops needing water');
assert.equal(irrigateGarden({...s,location:'home'}).state.location,'home');
const loaded=safeLoad(JSON.parse(JSON.stringify(r.state)));assert.equal(loaded.plots[0].watered,true);assert.equal(loaded.irrigationOpen,true,'open faucet persists');
assert.equal(safeLoad({...JSON.parse(JSON.stringify(s)),irrigationOpen:'yes'}),null,'reject invalid flag');
assert.ok(safeLoad(JSON.parse(JSON.stringify(s))),'old save without faucet flag loads');
const plant=applyFarmTool({...r.state,player:{x:5,y:9,dir:'up'}},'seed');assert.equal(plant.state.plots[2].watered,true,'open faucet supplies new plants');
const sleep={...r.state,location:'home',player:{x:9,y:8,dir:'up'}};assert.equal(nextDay(sleep).plots[0].watered,true,'open faucet remains active next morning');
const mature={x:4,y:8,stage:3,watered:false};
const byCrop={...s,player:{x:3,y:8,dir:'right'},plots:[mature]};
const wetAfterPicking=applyFarmTool({...byCrop,plots:[{...mature,watered:true}]},'harvest').state;
assert.equal(wetAfterPicking.plots[0].stage,1,'picking starts the next growth cycle');
assert.equal(wetAfterPicking.plots[0].watered,true,'harvest preserves water even when the tap is closed');
const dryAfterPicking=applyFarmTool(byCrop,'harvest').state;
assert.equal(dryAfterPicking.plots[0].watered,false,'picking a dry crop does not water it');
assert.equal(irrigateGarden({...dryAfterPicking,player:s.player}).state.plots[0].watered,true,'the faucet waters regrowth');
const openAfterPicking=applyFarmTool({...byCrop,irrigationOpen:true},'harvest').state;
assert.equal(openAfterPicking.plots[0].watered,true,'an open tap supplies the next harvest cycle');
const ripeTomorrow=nextDay({...sleep,plots:[{...mature,stage:2,watered:true}]}).plots[0];
assert.equal(ripeTomorrow.stage,3);
assert.equal(ripeTomorrow.watered,true,'the faucet supplies the crop on the morning it ripens');
const restored=safeLoad(JSON.parse(JSON.stringify({...byCrop,irrigationOpen:true})));
assert.equal(restored.plots[0].watered,true,'repair a legacy dry mature crop in a save with the faucet running');
assert.equal(safeLoad(JSON.parse(JSON.stringify(byCrop))).plots[0].watered,false,'closed faucet does not alter an old dry crop');
console.log('PASS: faucet toggle, channel access, crops, day transition and save migration');

const { IYAN_MARKET, POULTRY, INGGIT_WARUNG, interactPoultry, poultryStock, areaBlocked }=mod.exports;
const dayOne=newGame();
const visit={...dayOne,location:'pasar',minutes:9*60,player:{x:IYAN_MARKET.x,y:IYAN_MARKET.y+1,dir:'up'}};
assert.equal(getActionContext(visit).kind,'poultry-shop');
assert.equal(areaBlocked(visit.location,visit.player.x,visit.player.y,visit),false);
assert.equal(tapModule.exports.planTapRoute(visit,IYAN_MARKET.x,IYAN_MARKET.y)?.interact,true);
assert.equal(interactPoultry({...visit,minutes:8*60},'buy-feed').state.poultry,undefined);
const bought=interactPoultry(visit,'buy-feed').state;
assert.equal(bought.coins,dayOne.coins-POULTRY.feedPrice);
assert.equal(poultryStock(bought).feed,POULTRY.feedPack);
const byFeeder={...bought,location:'field',player:{x:POULTRY.feeder.x,y:POULTRY.feeder.y-1,dir:'down'}};
assert.equal(getActionContext(byFeeder).kind,'feed-chicken');
assert.equal(areaBlocked(byFeeder.location,byFeeder.player.x,byFeeder.player.y,byFeeder),false);
assert.equal(tapModule.exports.planTapRoute(byFeeder,POULTRY.feeder.x,POULTRY.feeder.y)?.interact,true);
const fed=interactPoultry(byFeeder,'feed').state;
assert.equal(poultryStock(fed).feed,POULTRY.feedPack-1);
assert.equal(interactPoultry(fed,'feed').state,fed);
assert.equal(poultryStock(fed).nest,0);
const morning=nextDay({...safeLoad(JSON.parse(JSON.stringify(fed))),location:'home',player:{x:9,y:8,dir:'up'}});
assert.equal(poultryStock(morning).nest,1);
assert.equal(poultryStock(nextDay(morning)).nest,1);
const byNest={...morning,location:'field',player:{x:POULTRY.nest.x,y:POULTRY.nest.y-1,dir:'down'}};
assert.equal(getActionContext(byNest).kind,'collect-eggs');
const gathered=interactPoultry(byNest,'collect').state;
assert.equal(poultryStock(gathered).nest,0);
const atInggit={...gathered,player:{x:INGGIT_WARUNG.x,y:INGGIT_WARUNG.y+1,dir:'up'}};
assert.equal(interactPoultry({...atInggit,minutes:18*60},'sell-eggs').state.poultry.eggs,1);
const sold=interactPoultry(atInggit,'sell-eggs').state;
assert.equal(sold.coins,bought.coins+POULTRY.eggPrice);
assert.equal(poultryStock(sold).eggs,0);
assert.equal(safeLoad({...sold,poultry:{...sold.poultry,fedDay:sold.day+1}}),null);
console.log('PASS: Iyan’s feed counter, touch targets, one feed per day, sleep, egg collection, Inggit sale and old saves');
